-- V004 · followup_snapshot 增加 extra_json
--
-- 背景：三体导出 38 列，其中 22 列能对上现有字段，16 列没有归属：
--   次卡_购买课时 / 次卡_已用课时 / 次卡_到期日 / 剩余课时合计 / 消耗情况 /
--   有效合同数 / 近60天到期数 / 买过的产品 / 会员列表消费 / 跟过老师数 /
--   跟过的老师 / 分配依据 / 取消次数 / 未到次数 / 首次上课 / 谈单提示
--
-- 决定（2026-11-10）：这 16 列原样存进 extra_json，不丢弃、也不逐列建字段。
--   丢弃 → 「取消次数/未到次数/首次上课」是判断爽约风险的原料，C2 很可能要用；
--   逐列加 → 现在没人查，白付 16 个字段的维护成本。
-- 需要时再 ALTER 提升成正式列，并用 UPDATE ... JSON_EXTRACT 回填。
--
-- 字段只用于留存原始数据，不参与任何查询条件，因此不建索引。
--
-- 设计：cycles/c1-followup/design.md 附录「CSV 列映射表」
-- ------------------------------------------------------------

ALTER TABLE followup_snapshot
  ADD COLUMN extra_json JSON NULL
  COMMENT '未映射的 16 个导出列，原样保存；不参与查询' AFTER talk_script;
